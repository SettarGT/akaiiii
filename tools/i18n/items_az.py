def lua_escape(s):
    return s.replace("\\", "\\\\").replace("'", "\\'")


def main():
    path = "resources/[qb]/qb-core/shared/items.lua"
    text = open(path, encoding="utf-8").read()
    out = []
    changed = 0
    # Lua string 'content' ola bilər: \' və \\ escape-lərini dəstəklə
    lua_str = r"'((?:[^'\\]|\\.)*)'"
    label_re = re.compile(r"label\s*=\s*" + lua_str)
    desc_re = re.compile(r"description\s*=\s*" + lua_str)

    for line in text.split("\n"):
        m = re.match(r"^(\s*\w+\s*=\s*\{\s*name\s*=\s*'([^']+)'.*)$", line)
        if m:
            key = m.group(2)
            if key in AZ_ITEMS:
                label, desc = AZ_ITEMS[key]
                line = label_re.sub(lambda mm: "label = '" + lua_escape(label) + "'", line, count=1)
                if desc:
                    line = desc_re.sub(lambda mm: "description = '" + lua_escape(desc) + "'", line, count=1)
                changed += 1
        out.append(line)
    open(path, "w", encoding="utf-8").write("\n".join(out))
    print("Translated %d items -> %s" % (changed, path))


if __name__ == "__main__":
    main()
